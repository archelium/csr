"""Regenerate sc_slate_ships.py: per-ship data for the Kestrel slate.

Sources (local, git-excluded design work):
  .superpowers/brainstorm/1287-1795499520/content/live-view-tablet.html
    ALLSHIPS  ship list, seats, turrets with per-mount guns and pilot/gunner control
    SHAPE     top-down outline and hardpoints from the game models
    SDIM      length, width, height and pilot gun ports
    SPEEDS    SCM, boost and NAV max
Those tables come from scunpacked-data, the game's Data.p4k models and its vehicle
definitions (see .superpowers/ship-data/*.py).

Run: py -3 tools/build_slate_ships.py
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOCK = os.path.join(HERE, ".superpowers", "brainstorm", "1287-1795499520", "content", "live-view-tablet.html")
OUT = os.path.join(HERE, "sc_slate_ships.py")
SAME_HULL = {"RSI_Apollo_Medivac_Tier_1": "RSI_Apollo_Medivac", "RSI_Apollo_Medivac_Tier_2": "RSI_Apollo_Medivac",
             "RSI_Apollo_Medivac_Tier_3": "RSI_Apollo_Medivac"}


def table(src, name):
    m = re.search(r"\nconst %s=([\[{].*?[\]}]);\n" % name, src, re.S)
    if not m:
        sys.exit(f"{name} not found in the mock")
    return json.loads(m.group(1))


def build():
    src = open(MOCK, encoding="utf-8").read()
    ships, shape, sdim, speeds = (table(src, n) for n in ("ALLSHIPS", "SHAPE", "SDIM", "SPEEDS"))
    out = {}
    for c in ships:
        k = c["class"]
        sp = speeds.get(k) or speeds.get(SAME_HULL.get(k, ""))
        row = {key: c.get(key) for key in ("name", "short", "career", "role", "seats", "vtol", "wings",
                                           "mining", "salvage", "tractor", "missiles", "turrets", "slaved",
                                           "pilotTurrets", "sys")}
        row["pilotGuns"] = c.get("pilotGunList") or []
        row["shape"] = shape.get(k)
        row["dims"] = sdim.get(k)
        row["speeds"] = sp
        out[k] = row
    blob = json.dumps(out, separators=(",", ":"), ensure_ascii=False)
    if "'''" in blob:
        sys.exit("ship data holds ''' and would break the module")
    body = (
        '"""Per-ship data for the Kestrel slate. GENERATED by tools/build_slate_ships.py, do not edit.\n'
        "Sources: scunpacked-data ships, the game's Data.p4k models and vehicle definitions.\"\"\"\n"
        "import json\n\n"
        f"SHIPS_JSON = r'''{blob}'''\n\n"
        "_SHIPS = None\n\n\n"
        "def ship_payload(cls):\n"
        '    """One ship\'s data, or None when the class is unknown. Case-insensitive."""\n'
        "    global _SHIPS\n"
        "    if not cls:\n"
        "        return None\n"
        "    if _SHIPS is None:\n"
        "        _SHIPS = {k.lower(): (k, v) for k, v in json.loads(SHIPS_JSON).items()}\n"
        "    hit = _SHIPS.get(str(cls).lower())\n"
        "    if not hit:\n"
        "        return None\n"
        "    return dict(hit[1], **{'class': hit[0]})\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print(f"{len(out)} ships, {len(blob):,} chars -> {OUT}")


if __name__ == "__main__":
    build()
