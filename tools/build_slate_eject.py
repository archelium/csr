"""Which seats can eject, from the game's own records (scunpacked's HasEjection misses many, the Marauder among them).

  py -3 tools/build_slate_eject.py D:/SC-Extract/dcb

Reads the converted Game2.dcb records (unforge): every spaceship and ground vehicle's default loadout names an
entity per seat hardpoint, and a seat entity that carries the "ejection" interaction can eject. Writes
sc_slate_eject.py: {ship class lowercased: [seat hardpoints that eject]}."""
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF_RE = re.compile(r'__ref="([0-9a-f-]{36})"')
EJECT_RE = re.compile(r'<[^>]*\bName="(?:ejection|eject)"', re.I)
PORT_RE = re.compile(r'itemPortName="([^"]*seat[^"]*)"\s+entityClassReference="([0-9a-f-]{36})"', re.I)


def seat_refs(records):
    """{seat entity guid: True when it carries the ejection interaction}."""
    out = {}
    for f in glob.glob(os.path.join(records, "entities", "scitem", "ships", "seat", "*.xml")):
        with open(f, encoding="utf-8", errors="replace") as fh:
            t = fh.read()
        m = REF_RE.search(t)
        if m:
            out[m.group(1)] = bool(EJECT_RE.search(t))
    return out


def build(dcb):
    records = os.path.join(dcb, "libs", "foundry", "records")
    seats = seat_refs(records)
    out = {}
    for kind in ("spaceships", "groundvehicles"):
        for f in sorted(glob.glob(os.path.join(records, "entities", kind, "*.xml"))):
            with open(f, encoding="utf-8", errors="replace") as fh:
                t = fh.read()
            ej = sorted({port for port, ref in PORT_RE.findall(t) if seats.get(ref)})
            if ej:
                out[os.path.basename(f)[:-4].lower()] = ej
    return out


def main():
    dcb = sys.argv[1] if len(sys.argv) > 1 else r"D:\SC-Extract\dcb"
    data = build(dcb)
    body = json.dumps(data, sort_keys=True, separators=(",", ":"))
    with open(os.path.join(HERE, "sc_slate_eject.py"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write('"""Seats that can eject, per ship class (lowercased). Generated by tools/build_slate_eject.py '
                 'from the game\'s records. Do not edit."""\nimport json\n\n'
                 "EJECT = json.loads(r'''" + body + "''')\n")
    print(len(data), "ships with an ejecting seat")


if __name__ == "__main__":
    main()
